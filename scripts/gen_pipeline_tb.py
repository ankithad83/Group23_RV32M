#!/usr/bin/env python3
"""Assemble tb/pipeline_test.S and write tb/tb_pipeline.v (pure Verilog, program embedded)."""
import subprocess, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = os.path.join(ROOT, "tb")
subprocess.check_call(["riscv64-unknown-elf-gcc", "-march=rv32im", "-mabi=ilp32", "-nostdlib", "-nostartfiles",
                       "-Ttext=0", "-o", "/tmp/pt.elf", os.path.join(T, "pipeline_test.S")])
subprocess.check_call(["riscv64-unknown-elf-objcopy", "-O", "binary", "/tmp/pt.elf", "/tmp/pt.bin"])
data = open("/tmp/pt.bin", "rb").read()
words = [int.from_bytes(data[i:i+4], "little") for i in range(0, len(data), 4)]
init = "\n".join(f"        imem[{i}] = 32'h{w:08x};" for i, w in enumerate(words))
tb = f'''// =============================================================================
// tb_pipeline.v  --  GENERATED by scripts/gen_pipeline_tb.py from tb/pipeline_test.S
// Directed test of the pipeline against the slide-3 timing diagram: prints the
// cycle in which each instruction is in EX (cycle 1 = IF of the first lw) and
// checks the final register values (load-use, forwarding, flush, MUL/DIV stalls).
// Run: iverilog -g2005 -o tb_pipeline tb_pipeline.v ../rtl/rv32im_core.v ../rtl/alu.v \\
//        ../rtl/regfile.v ../rtl/decoder.v ../rtl/hazard_unit.v ../rtl/forward_unit.v \\
//        ../rtl/m_unit.v ../rtl/mul_unit.v ../rtl/div_unit.v && vvp tb_pipeline
// =============================================================================
`timescale 1ns/1ps
module tb_pipeline;
    reg clk = 0, rst = 1;
    always #5 clk = ~clk;

    reg [31:0] imem [0:255];
    reg [31:0] dmem [0:1023];
    wire [31:0] imem_addr, dmem_addr, dmem_wdata;
    wire [3:0]  dmem_be;
    wire        dmem_we, retire, stall_hold;
    wire [31:0] imem_data  = imem[imem_addr[9:2]];
    wire [31:0] dmem_rdata = dmem[dmem_addr[11:2]];

    rv32im_core dut (.clk(clk), .rst(rst), .imem_addr(imem_addr), .imem_data(imem_data),
        .dmem_addr(dmem_addr), .dmem_wdata(dmem_wdata), .dmem_be(dmem_be), .dmem_we(dmem_we),
        .dmem_rdata(dmem_rdata), .retire(retire), .stall_hold(stall_hold));

    always @(posedge clk) if (dmem_we) dmem[dmem_addr[11:2]] <= dmem_wdata;   // word stores only here

    integer i, errors, cyc, t0;
    reg [31:0] ex_cycle [0:63];            // cycle in which each pc is in EX (last cycle for multi-cycle ops)
    reg [31:0] ex_first [0:63];
    initial begin
        for (i = 0; i < 256; i = i + 1) imem[i] = 32'h00000013;
{init}
        for (i = 0; i < 1024; i = i + 1) dmem[i] = 0;
        dmem[32'h100 >> 2] = 32'd5;
        for (i = 0; i < 64; i = i + 1) begin ex_cycle[i] = 0; ex_first[i] = 0; end
        errors = 0; cyc = 0;
        repeat (3) @(posedge clk);
        #1 rst = 0;
    end

    // record when each instruction is in EX (cycle counter restarts at the first lw)
    always @(posedge clk) begin
        if (!rst) begin
            cyc = cyc + 1;
            if (dut.idex_valid) begin
                if (ex_first[dut.idex_pc[7:2]] == 0) ex_first[dut.idex_pc[7:2]] = cyc;
                ex_cycle[dut.idex_pc[7:2]] = cyc;
            end
        end
    end

    task check_reg(input integer r, input [31:0] exp, input [8*8-1:0] nm);
        begin
            if (dut.u_rf.regs[r] !== exp) begin
                errors = errors + 1;
                $display("FAIL %0s (x%0d) = %0d, expected %0d", nm, r, dut.u_rf.regs[r], exp);
            end
        end
    endtask

    task check_ex(input [7:0] pc, input integer first, input integer last, input [8*10-1:0] nm);
        integer f, l;
        begin
            f = ex_first[pc[7:2]] - t0 + 1;  l = ex_cycle[pc[7:2]] - t0 + 1;
            $display("  %0s EX cycles %0d..%0d   (expected %0d..%0d)", nm, f, l, first, last);
            if (f != first || l != last) errors = errors + 1;
        end
    endtask

    initial begin
        #4000000;                                   // ~400k cycles is far more than needed
        $finish;
    end

    initial begin
        wait (!rst);
        repeat (400) @(posedge clk);
        #1;
        // cycle 1 of the diagram = IF of lw (pc 0x20) -> its EX is cycle 2
        t0 = ex_first[8] - 1;                       // lw @0x20 -> index 8
        $display("Pipeline timing vs the slide-3 diagram (cycle 1 = IF of lw):");
        check_ex(8'h20, 2,  2,  "lw       ");
        check_ex(8'h24, 4,  4,  "add (use)");
        check_ex(8'h28, 5,  5,  "bne      ");
        if (ex_first[8'h2c >> 2] != 0) begin errors = errors + 1; $display("  FAIL: wrong-path sub reached EX"); end
        else $display("  sub (wrong path) never reaches EX: flushed");
        check_ex(8'h38, 7,  8,  "mul      ");
        check_ex(8'h3c, 9,  9,  "add (fwd)");
        check_ex(8'h40, 10, 43, "div      ");
        check_ex(8'h44, 44, 44, "addi     ");
        check_reg(5, 5, "lw");        check_reg(6, 12, "add");   check_reg(14, 99, "flushed");
        check_reg(8, 72, "mul");      check_reg(10, 144, "add2"); check_reg(11, 28, "div");
        check_reg(13, 29, "addi");    check_reg(4, 5, "chain");  check_reg(15, 5, "sw/lw");
        check_reg(16, 6, "lu2");      check_reg(17, 36, "mul2"); check_reg(18, 216, "mul3");
        check_reg(19, 36, "divu");    check_reg(20, 6, "rem");
        if (errors == 0) $display("PASS: pipeline timing and results match the diagram");
        else             $display("FAIL: %0d check(s) failed", errors);
        $finish;
    end
endmodule
'''
open(os.path.join(T, "tb_pipeline.v"), "w").write(tb)
print("wrote tb/tb_pipeline.v,", len(words), "words")
