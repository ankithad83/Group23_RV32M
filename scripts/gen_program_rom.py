#!/usr/bin/env python3
"""
gen_program_rom.py -- embed the compiled programs into rtl/program_rom.v
(Vivado reads only .v, so the program lives in a Verilog case-ROM).

  cd sw && make && cd .. && python3 scripts/gen_program_rom.py

prog_sel   program
  0..4     matmul, gcd, factorial, fir, primes   (rv32im: hardware MUL/DIV)
  5..9     matmul, gcd, factorial, fir, primes   (rv32i : software mul/div)
  10       isa_test                              (rv32im self-check)
256 words (1 KB) per program.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, "sw", "build")
PROGS = ["matmul", "gcd", "factorial", "fir", "primes"]
SLOTS = [("rv32im", p) for p in PROGS] + [("rv32i", p) for p in PROGS] + [("rv32im", "isa_test")]
DEPTH = 256

out = []
out.append("`timescale 1ns/1ps")
out.append("// =============================================================================")
out.append("// program_rom.v  --  GENERATED by scripts/gen_program_rom.py, do not edit by hand")
out.append("// Instruction memory contents for every test program (see the script header).")
out.append("// Asynchronous read; unlisted words read as NOP (addi x0,x0,0).")
out.append("// =============================================================================")
out.append("module program_rom (")
out.append("    input  wire [3:0]  sel,")
out.append("    input  wire [7:0]  addr,      // word address = pc[9:2]")
out.append("    output reg  [31:0] data")
out.append(");")
out.append("    always @(*) begin")
out.append("        case ({sel, addr})")
for k, (arch, prog) in enumerate(SLOTS):
    path = os.path.join(B, arch, prog + ".mem")
    words = [int(l, 16) for l in open(path) if l.strip()]
    if len(words) > DEPTH:
        sys.exit(f"{arch}/{prog}: {len(words)} words > {DEPTH}")
    out.append(f"            // sel {k}: {prog} ({arch}), {len(words)} words")
    for a, w in enumerate(words):
        out.append(f"            12'h{k:01x}{a:02x}: data = 32'h{w:08x};")
out.append("            default: data = 32'h00000013;")
out.append("        endcase")
out.append("    end")
out.append("endmodule")
open(os.path.join(ROOT, "rtl", "program_rom.v"), "w").write("\n".join(out) + "\n")
print("wrote rtl/program_rom.v:", sum(1 for l in out if "data = 32'h" in l) - 1, "words")
